const LANGUAGE_STORAGE_KEY = "viki-portfolio-language";
let currentLanguage = "zh";

function storedLanguage() {
  try {
    return localStorage.getItem(LANGUAGE_STORAGE_KEY);
  } catch {
    return null;
  }
}

function saveLanguage(language) {
  try {
    localStorage.setItem(LANGUAGE_STORAGE_KEY, language);
  } catch {
    // The language still works when storage is unavailable.
  }
}

function updateAudioLabels() {
  const action = currentLanguage === "zh"
    ? { play: "播放", pause: "暂停" }
    : { play: "Play", pause: "Pause" };

  document.querySelectorAll(".track-play").forEach((button) => {
    const verb = button.classList.contains("is-playing") ? action.pause : action.play;
    button.setAttribute("aria-label", `${verb} ${button.dataset.track}`);
  });
}

function applyLanguage(language, preservePosition = false) {
  const anchor = preservePosition
    ? document.elementFromPoint(window.innerWidth / 2, window.innerHeight / 2)?.closest("section, article")
    : null;
  const previousTop = anchor?.getBoundingClientRect().top ?? 0;

  currentLanguage = language === "en" ? "en" : "zh";
  const content = COPY[currentLanguage];

  document.documentElement.lang = currentLanguage === "zh" ? "zh-CN" : "en";
  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const value = content[element.dataset.i18n];
    if (typeof value === "string") element.textContent = value;
  });
  document.querySelectorAll("[data-i18n-html]").forEach((element) => {
    const value = content[element.dataset.i18nHtml];
    if (typeof value === "string") element.innerHTML = value;
  });
  document.querySelectorAll("[data-alt-key]").forEach((element) => {
    const value = content[element.dataset.altKey];
    if (typeof value === "string") element.alt = value;
  });

  const switchButton = document.getElementById("languageSwitch");
  const switchingToEnglish = currentLanguage === "zh";
  switchButton.textContent = switchingToEnglish ? "EN" : "中文";
  switchButton.setAttribute("aria-label", switchingToEnglish ? "Switch to English" : "切换到中文");

  document.getElementById("workflowDiagramZh").hidden = currentLanguage !== "zh";
  document.getElementById("workflowDiagramEn").hidden = currentLanguage !== "en";

  const description = currentLanguage === "zh"
    ? "Viki 的个人作品集：从真实使用中的小摩擦出发，用产品思维、工程能力与 AI 辅助工作方式把想法真正做出来。"
    : "Viki’s personal portfolio: product thinking, engineering, AI-assisted workflows, and creative practices that turn observations into real things.";
  document.querySelector('meta[name="description"]')?.setAttribute("content", description);
  document.title = currentLanguage === "zh" ? "Viki — 个人作品集" : "Viki — Personal Portfolio";

  updateAudioLabels();
  saveLanguage(currentLanguage);

  if (anchor) {
    const currentTop = anchor.getBoundingClientRect().top;
    window.scrollBy(0, currentTop - previousTop);
  }
}

const productTabs = [...document.querySelectorAll(".product-tab")];
const productDetails = [...document.querySelectorAll("[data-product-detail]")];
const productSlides = [...document.querySelectorAll("[data-product-slide]")];
const productStageIndex = document.querySelector(".stage-index");
let activeProduct = productTabs[0]?.dataset.product || "picpop";

function activateProduct(product, shouldFocus = false, shouldAnimate = true) {
  const nextProduct = productTabs.some((tab) => tab.dataset.product === product) ? product : activeProduct;
  const activeIndex = productTabs.findIndex((tab) => tab.dataset.product === nextProduct);
  activeProduct = nextProduct;

  productTabs.forEach((tab) => {
    const isActive = tab.dataset.product === nextProduct;
    tab.classList.toggle("is-active", isActive);
    tab.setAttribute("aria-selected", String(isActive));
    tab.tabIndex = isActive ? 0 : -1;
    if (isActive && shouldFocus) tab.focus();
  });

  productDetails.forEach((detail) => {
    const isActive = detail.dataset.productDetail === nextProduct;
    detail.hidden = detail.dataset.productDetail !== nextProduct;
    detail.classList.toggle("is-transitioning", isActive && shouldAnimate);
  });
  productSlides.forEach((slide) => {
    const isActive = slide.dataset.productSlide === nextProduct;
    slide.hidden = slide.dataset.productSlide !== nextProduct;
    slide.classList.toggle("is-transitioning", isActive && shouldAnimate);
  });
  if (productStageIndex && activeIndex >= 0) {
    productStageIndex.textContent = `${String(activeIndex + 1).padStart(2, "0")} / ${String(productTabs.length).padStart(2, "0")}`;
  }

  if (shouldAnimate) {
    window.setTimeout(() => {
      productDetails.forEach((detail) => detail.classList.remove("is-transitioning"));
      productSlides.forEach((slide) => slide.classList.remove("is-transitioning"));
    }, 420);
  }
}

productTabs.forEach((tab, index) => {
  tab.addEventListener("click", () => activateProduct(tab.dataset.product, false, true));
  tab.addEventListener("keydown", (event) => {
    const direction = event.key === "ArrowRight" || event.key === "ArrowDown" ? 1
      : event.key === "ArrowLeft" || event.key === "ArrowUp" ? -1
      : event.key === "Home" ? -productTabs.length
      : event.key === "End" ? productTabs.length
      : 0;
    if (!direction) return;
    event.preventDefault();
    const nextIndex = direction === productTabs.length ? productTabs.length - 1
      : direction === -productTabs.length ? 0
      : (index + direction + productTabs.length) % productTabs.length;
    activateProduct(productTabs[nextIndex].dataset.product, true, true);
  });
});

activateProduct(activeProduct, false, false);

