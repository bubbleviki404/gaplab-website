let activeAudio = null;
let activeButton = null;

function setAudioButtonState(button, playing) {
  button.classList.toggle("is-playing", playing);
  button.setAttribute("aria-pressed", String(playing));
  updateAudioLabels();
}

document.querySelectorAll(".track-play").forEach((button) => {
  const audio = document.getElementById(button.dataset.audioId);
  button.setAttribute("aria-pressed", "false");

  button.addEventListener("click", async () => {
    if (activeAudio === audio && !audio.paused) {
      audio.pause();
      return;
    }

    if (activeAudio && activeAudio !== audio) {
      activeAudio.pause();
      activeAudio.currentTime = 0;
    }

    activeAudio = audio;
    activeButton = button;

    try {
      await audio.play();
      setAudioButtonState(button, true);
    } catch {
      setAudioButtonState(button, false);
    }
  });

  audio.addEventListener("pause", () => {
    setAudioButtonState(button, false);
  });

  audio.addEventListener("ended", () => {
    audio.currentTime = 0;
    setAudioButtonState(button, false);
    if (activeAudio === audio) {
      activeAudio = null;
      activeButton = null;
    }
  });
});

